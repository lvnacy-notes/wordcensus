import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import copyStaticFiles from 'esbuild-copy-static-files';
import path from 'path';
import packageJson from './package.json' with { type: 'json' };

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Always build to ./dist/ - no vault path baked into the build tool. Point
// your local dev vault's plugin folder at this directory with a one-time
// symlink instead. Every other dev/prod distinction (sourcemaps, NODE_ENV,
// watch-vs-rebuild below) branches on `prod`; only the output *location* is
// not conditional.
const outdir = './dist/';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['main.ts', 'styles.css'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	// ES2020 is the floor, settled against Obsidian's real runtime range
	// rather than "current Electron": desktop Electron can lag the app's own
	// auto-updater, and mobile is a WKWebView (iOS) or system WebView
	// (Android), where some engine features arrive only with specific OS
	// versions (e.g. regex lookbehind needs iOS 16.4+). Matches
	// tsconfig.json's target exactly - esbuild only downlevels syntax, not
	// missing runtime APIs, so the two numbers agreeing is what "confirmed
	// compatible" means here. Runtime APIs newer than ES2020 (notably
	// Intl.Segmenter) need a feature-detected fallback in source.
	target: 'es2020',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	minifySyntax: true,
	plugins: [
		copyStaticFiles({
			src: './manifest.json',
			dest: path.join(outdir, 'manifest.json'),
		}),
	],
	outdir: outdir,
	define: {
		'process.env.NODE_ENV': prod ? '"production"' : '"development"',
		'process.env.PLUGIN_VERSION': `'${ packageJson.version }'`,
		'process.env.EMULATE_MOBILE': prod
			? 'false'
			: process.argv.includes('--mobile').toString(),
	},
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
	await context.serve(); // This enables the 'live reload'
}
